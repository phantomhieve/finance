def _extract_allocation_slice(data: dict) -> dict:
    """Extract only allocation, concentration, and liquidity tier data."""
    return {
        "summary": data.get("summary", {}),
        "asset_allocation": data.get("asset_allocation", []),
        "consolidated": data.get("consolidated", []),
        "stocks_consolidated": [
            {
                "symbol": s.get("symbol"),
                "total_current": s.get("total_current"),
                "pct_of_portfolio": s.get("pct_of_portfolio"),
                "total_pnl_pct": s.get("total_pnl_pct"),
            }
            for s in data.get("stocks_consolidated", [])[:15]
        ],
        "us_stocks_rsu": data.get("us_stocks_rsu", []),
        "us_stocks_total": data.get("us_stocks_total", {}),
        "cash": data.get("cash", {}),
        "fixed_deposits": data.get("fixed_deposits", {}),
        "epf": data.get("epf", {}),
        "nps": data.get("nps", {}),
        "commodities": {
            "total_value": (data.get("commodities") or {}).get("total_value"),
            "pct_of_portfolio": (data.get("commodities") or {}).get("pct_of_portfolio"),
        },
        "real_estate_summary": {
            "total_current": (data.get("real_estate") or {}).get("total_current"),
            "pct_of_portfolio": (data.get("real_estate") or {}).get("pct_of_portfolio"),
        },
    }


def _extract_quality_slice(data: dict) -> dict:
    """Extract holding-level quality, legacy funds, real estate parcels, and fixed debt."""
    return {
        "stocks_consolidated": [
            {
                "symbol": s.get("symbol"),
                "total_invested": s.get("total_invested"),
                "total_current": s.get("total_current"),
                "total_pnl": s.get("total_pnl"),
                "total_pnl_pct": s.get("total_pnl_pct"),
            }
            for s in data.get("stocks_consolidated", [])[:20]
        ],
        "mutual_funds_active_sip": data.get("mutual_funds_active_sip", []),
        "mutual_funds_legacy": data.get("mutual_funds_legacy", []),
        "real_estate_holdings": [
            {
                "name": h.get("name"),
                "property_type": h.get("property_type"),
                "acquisition_type": h.get("acquisition_type"),
                "micro_market_tag": h.get("micro_market_tag"),
                "location_summary": h.get("location_summary"),
                "cost_basis": h.get("cost_basis"),
                "current_valuation": h.get("current_valuation"),
                "cagr_pct": h.get("cagr_pct"),
                "rental_yield_pct": h.get("rental_yield_pct"),
            }
            for h in (data.get("real_estate") or {}).get("holdings", [])
        ],
        "fixed_deposits": data.get("fixed_deposits", {}),
        "epf": data.get("epf", {}),
    }


def _extract_macro_stress_slice(data: dict) -> dict:
    """Extract macro indicators, equity allocation, RSU, crypto, and growth momentum."""
    return {
        "summary": data.get("summary", {}),
        "asset_allocation": data.get("asset_allocation", []),
        "macro_context": data.get("macro_context", {}),
        "us_stocks_total": data.get("us_stocks_total", {}),
        "crypto": data.get("crypto", {}),
        "growth_history": data.get("growth_history", [])[-6:],  # Last 6 months for trajectory
    }


