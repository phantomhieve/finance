def run_stage_1a_allocation(data: dict, investor_profile: str) -> AllocationLensResult:
    """Stage 1A: Allocation, Concentration, and Liquidity Lens."""
    logger.debug("[DAG] Executing Stage 1A: Allocation & Liquidity Node")
    subset = _extract_allocation_slice(data)
    prompt = f"""\
You are an expert quantitative asset allocation analyst for Indian family wealth.
Analyze the provided portfolio slice strictly against these criteria:

1. Asset Allocation vs Age Glide Path:
   - Compare asset class mix against the investor profile. For age 25-35, norm is ~70-80% growth, ~20-30% stability.
2. Concentration & HHI:
   - Identify stocks > 5% (warning) or > 10% (critical) of total portfolio.
   - Dual employer exposure: assess RSU value + salary dependency.
   - Single asset class > 50% warning.
3. Liquidity Tiers & Emergency Floor:
   - Tier 1 (instant: listed equity + cash).
   - Tier 2 (1-7 days: FDs, RSU T+2).
   - Tier 3 (locked/illiquid: EPF, NPS, physical gold, real estate).
   - Does Tier 1 cover 6 months of household emergency expenses?

Assign a calibrated sub_score (0-100) reflecting diversification and liquidity hygiene.
Generate 2-4 candidate Insight objects for this lens.

Investor Profile:
{investor_profile}

Portfolio Slice:
{json.dumps(subset, cls=_DecimalEncoder, indent=2)}
"""
    return gateway.generate_structured(
        schema=AllocationLensResult,
        prompt=prompt,
        task=TaskType.FAST,
        temperature=0.1,
    )


def run_stage_1b_quality(data: dict, investor_profile: str) -> QualityLensResult:
    """Stage 1B: Asset Quality, Fund Audit, and Real Estate Appraisal Lens."""
    logger.debug("[DAG] Executing Stage 1B: Asset Quality & Audit Node")
    subset = _extract_quality_slice(data)
    prompt = f"""\
You are a senior asset quality and fund portfolio manager for Indian family wealth.
Evaluate the provided asset holdings slice strictly against these fiduciary standards:

1. Equity Quality & Behavioral Flags:
   - Top gainers and loss leaders. Flag loss aversion / anchoring on stocks with pnl_pct < -15%.
2. Legacy Mutual Fund Audit:
   - For EACH fund in mutual_funds_legacy, formulate a concrete action: 'hold', 'merge into [name a specific active fund and why]', or 'exit'.
3. Real Estate Micro-Market Quality:
   - For each holding, evaluate corridor/locality catalysts (expressways, metro, airport), rental yield vs 2-4% norm, and CAGR vs 8-12% land benchmark.
   - Distinguish INHERITED (zero investor out-of-pocket, legacy capital) vs purchased properties.
4. Fixed Debt Quality:
   - Compare FD rates against EPF ~8.15% tax-free hurdle (~11.5% pre-tax equivalent).

Assign a calibrated sub_score (0-100) reflecting asset quality and active fund efficiency.
Generate 2-4 candidate Insight objects for this lens.

Investor Profile:
{investor_profile}

Portfolio Slice:
{json.dumps(subset, cls=_DecimalEncoder, indent=2)}
"""
    return gateway.generate_structured(
        schema=QualityLensResult,
        prompt=prompt,
        task=TaskType.FAST,
        temperature=0.1,
    )


